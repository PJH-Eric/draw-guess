  function cubeFace(o, u, v, cols) {
    var L = [],
      i,
      j,
      k = 0;
    for (i = 0; i < 3; i++)
      for (j = 0; j < 3; j++) {
        var p = function (a, b) {
          return [
            o[0] + (u[0] * a) / 3 + (v[0] * b) / 3,
            o[1] + (u[1] * a) / 3 + (v[1] * b) / 3,
          ];
        };
        var a = p(i, j),
          b = p(i + 1, j),
          c = p(i + 1, j + 1),
          d = p(i, j + 1);
        L.push([
          cols[k++ % cols.length],
          'M' +
            a.join(' ') +
            'L' +
            b.join(' ') +
            'L' +
            c.join(' ') +
            'L' +
            d.join(' ') +
            'Z',
          { w: 7 },
        ]);
      }
    return L;
  }

