  /** 正規化玩家輸入：去掉空白、標點、全形轉半形，方便比對 */
  function normalize(text) {
    var s = String(text === undefined || text === null ? '' : text);
    s = s.replace(/[\s　]+/g, '');
    s = s.replace(/[，。！？、,.!?~～·「」『』（）()\[\]【】:：;；"'`]/g, '');
    s = s.replace(/[！-～]/g, function (ch) {
      return String.fromCharCode(ch.charCodeAt(0) - 0xFEE0);
    });
    return s.toLowerCase();
  }

  /** 猜測是否命中；回傳 'hit' | 'close' | 'miss' */
  function match(word, guess) {
    var g = normalize(guess);
    if (!g) return 'miss';
    var names = [word.text].concat(word.alt || []);
    var i;
    for (i = 0; i < names.length; i++) {
      if (normalize(names[i]) === g) return 'hit';
    }
    /* 差一個字（多打、少打、寫錯）算「很接近」，只私下提示猜的人 */
    for (i = 0; i < names.length; i++) {
      if (editDistance(normalize(names[i]), g) === 1) return 'close';
    }
    return 'miss';
  }

  function editDistance(a, b) {
    if (Math.abs(a.length - b.length) > 1) return 9;
    var m = a.length, n2 = b.length;
    var prev = new Array(n2 + 1);
    var cur = new Array(n2 + 1);
    for (var j = 0; j <= n2; j++) prev[j] = j;
    for (var i = 1; i <= m; i++) {
      cur[0] = i;
      for (var k = 1; k <= n2; k++) {
        cur[k] = Math.min(prev[k] + 1, cur[k - 1] + 1, prev[k - 1] + (a[i - 1] === b[k - 1] ? 0 : 1));
      }
      for (var c = 0; c <= n2; c++) prev[c] = cur[c];
    }
    return prev[n2];
  }

  /** 依難度挑選候選題目；用可注入的種子亂數，讓同一場對局可以重播 */
  function pick(rng, count, opts) {
    var o = opts || {};
    var pool = LIST.filter(function (w) {
      if (o.diff && w.diff !== o.diff) return false;
      if (o.cat && w.cat !== o.cat) return false;
      if (o.exclude && o.exclude.indexOf(w.id) >= 0) return false;
      return true;
    });
    if (!pool.length) pool = LIST.slice();
    var next = rng || Math.random;
    var out = [];
    var taken = {};
    var guard = 0;
    while (out.length < count && guard < 500) {
      guard += 1;
      var w2 = pool[Math.floor(next() * pool.length) % pool.length];
      if (taken[w2.id]) continue;
      taken[w2.id] = true;
      out.push(w2.id);
    }
    return out;
  }

