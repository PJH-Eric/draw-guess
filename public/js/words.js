  function ringPoints(cx, cy, rx, ry, a0, a1, rot, steps) {
    var pts = [];
    var n = steps || Math.max(12, Math.round(Math.abs(a1 - a0) / 12));
    var cos = Math.cos((rot || 0) * RAD);
    var sin = Math.sin((rot || 0) * RAD);
    for (var i = 0; i <= n; i++) {
      var a = (a0 + (a1 - a0) * (i / n)) * RAD;
      var x = Math.cos(a) * rx;
      var y = Math.sin(a) * ry;
      pts.push(cx + x * cos - y * sin, cy + x * sin + y * cos);
    }
    return pts;
  }

  /** 把一個指令展開成 0..n 筆（每筆是一個點陣列） */
  function opStrokes(op) {
    var k = op[0];
    var a = op;
    switch (k) {
      case 'c':  return [ringPoints(a[1], a[2], a[3], a[3], 0, 360, 0)];
      case 'e':  return [ringPoints(a[1], a[2], a[3], a[4], 0, 360, a[5] || 0)];
      case 'a':  return [ringPoints(a[1], a[2], a[3], a[3], a[4], a[5] < a[4] ? a[5] + 360 : a[5], 0)];
      case 'ae': return [ringPoints(a[1], a[2], a[3], a[4], a[5], a[6] < a[5] ? a[6] + 360 : a[6], 0)];
      case 'r':  return [[a[1], a[2], a[1] + a[3], a[2], a[1] + a[3], a[2] + a[4], a[1], a[2] + a[4], a[1], a[2]]];
      case 'l':  return [[a[1], a[2], a[3], a[4]]];
      case 'p':  return [a.slice(1)];
      case 's':  return [a.slice(1).concat([a[1], a[2]])];
      case 'd':  return [ringPoints(a[1], a[2], a[3] || 16, a[3] || 16, 0, 360, 0, 10)];
      case 'ray': {
        var out = [];
        var n = a[5] || 6;
        var off = (a[6] || 0);
        for (var i = 0; i < n; i++) {
          var ang = (off + i * 360 / n) * RAD;
          out.push([
            a[1] + Math.cos(ang) * a[3], a[2] + Math.sin(ang) * a[3],
            a[1] + Math.cos(ang) * a[4], a[2] + Math.sin(ang) * a[4]
          ]);
        }
        return out;
      }
      case 'w': {
        var pts = [];
        var segs = Math.max(1, a[5] || 3) * 12;
        for (var j = 0; j <= segs; j++) {
          var t = j / segs;
          pts.push(a[1] + (a[2] - a[1]) * t, a[3] + Math.sin(t * Math.PI * 2 * (a[5] || 3)) * a[4]);
        }
        return [pts];
      }
      case 'st': {
        var sp = [];
        var arms = a[5] || 5;
        for (var m = 0; m < arms * 2; m++) {
          var r = (m % 2 === 0) ? a[3] : a[4];
          var ang2 = (-90 + m * 180 / arms) * RAD;
          sp.push(a[1] + Math.cos(ang2) * r, a[2] + Math.sin(ang2) * r);
        }
        sp.push(sp[0], sp[1]);
        return [sp];
      }
      default: return [];
    }
  }

  var strokeCache = {};

  /**
   * 取得一題的配方筆畫。
   * @returns {Array<{p:number[]}>} 每筆是 [x0,y0,x1,y1,...]，座標都在 0..1000
   */
  function strokesOf(id) {
    if (strokeCache[id]) return strokeCache[id];
    var word = byId(id);
    if (!word) return [];
    var out = [];
    for (var i = 0; i < word.draw.length; i++) {
      var parts = opStrokes(word.draw[i]);
      for (var j = 0; j < parts.length; j++) {
        if (parts[j].length >= 4) out.push({ p: parts[j] });
      }
    }
    strokeCache[id] = out;
    return out;
  }

  /* ================================================================
     形狀特徵：電腦對手「看畫猜題」用的唯一資訊來源
     只吃筆畫幾何，不碰答案。人類手繪與配方都走同一支函式。
     ================================================================ */

  var DIRS = 8;

  /**
   * @param {Array<{p:number[]}>} strokes 筆畫（座標可以是任何尺度）
   * @returns {object|null} 正規化後的特徵向量
   */
  function features(strokes) {
    if (!strokes || !strokes.length) return null;
    var minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    var i, j, p;
    var total = 0;
    for (i = 0; i < strokes.length; i++) {
      p = strokes[i].p;
      for (j = 0; j < p.length; j += 2) {
        if (p[j] < minX) minX = p[j];
        if (p[j] > maxX) maxX = p[j];
        if (p[j + 1] < minY) minY = p[j + 1];
        if (p[j + 1] > maxY) maxY = p[j + 1];
        total += 1;
      }
    }
    if (!isFinite(minX) || total < 2) return null;
    var w = Math.max(1, maxX - minX);
    var h = Math.max(1, maxY - minY);
    var scale = Math.max(w, h);

    var dir = new Array(DIRS).fill(0);
    var grid = new Array(16).fill(0);       // 4×4 墨水分布
    var length = 0;
    var cells = 0;

    for (i = 0; i < strokes.length; i++) {
      p = strokes[i].p;
      for (j = 0; j + 3 < p.length; j += 2) {
        var x0 = p[j], y0 = p[j + 1], x1 = p[j + 2], y1 = p[j + 3];
        var dx = x1 - x0, dy = y1 - y0;
        var seg = Math.sqrt(dx * dx + dy * dy);
        if (seg < 1e-6) continue;
        length += seg;
        /* 方向長條圖：180 度對稱（畫筆從哪一頭畫不影響形狀） */
        var ang = Math.atan2(dy, dx);
        if (ang < 0) ang += Math.PI;
        var bin = Math.min(DIRS - 1, Math.floor(ang / Math.PI * DIRS));
        dir[bin] += seg;
        /* 墨水分布：把線段中點丟進 4×4 格 */
        var gx = Math.min(3, Math.max(0, Math.floor(((x0 + x1) / 2 - minX) / w * 4)));
        var gy = Math.min(3, Math.max(0, Math.floor(((y0 + y1) / 2 - minY) / h * 4)));
        grid[gy * 4 + gx] += seg;
      }
    }
    if (length < 1e-6) return null;
    for (i = 0; i < DIRS; i++) dir[i] /= length;
    for (i = 0; i < 16; i++) { if (grid[i] > 0) cells += 1; grid[i] /= length; }

    return {
      strokes: strokes.length,
      aspect: w / h,
      /* 墨水長度相對於外框：越大代表線條越密 */
      density: length / scale,
      coverage: cells / 16,
      dir: dir,
      grid: grid
    };
  }

  /** 兩組特徵的距離（0 = 完全一樣，越大越不像） */
  function distance(a, b) {
    if (!a || !b) return Infinity;
    var d = 0, i;
    for (i = 0; i < DIRS; i++) d += Math.abs(a.dir[i] - b.dir[i]) * 1.6;
    for (i = 0; i < 16; i++) d += Math.abs(a.grid[i] - b.grid[i]) * 1.1;
    d += Math.abs(Math.log(Math.max(0.1, a.aspect)) - Math.log(Math.max(0.1, b.aspect))) * 0.55;
    d += Math.min(1.2, Math.abs(a.density - b.density) / 14) * 0.5;
    d += Math.abs(a.coverage - b.coverage) * 0.7;
    d += Math.min(1, Math.abs(a.strokes - b.strokes) / 14) * 0.35;
    return d;
  }

