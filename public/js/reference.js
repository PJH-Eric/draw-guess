  function pointsOf(op) {
    // Share the existing shape converter without changing the game's recipes.
    return Words.pointsOf(op)
      .filter(function (p) {
        return p.length >= 4;
      })
      .map(function (p) {
        return { p: p };
      });
  }

  function get(id) {
    var word = Words.byId(id);
    if (!word) return null;
    if (recipes[word.text])
      return [].concat.apply([], recipes[word.text].map(pointsOf));
    if (id.indexOf('w-') === 0) return null;
    return Words.strokesOf(id);
  }

  function svg(id, step) {
    var strokes = get(id);
    if (!strokes) return '';
    var count = Math.ceil(
      (strokes.length * Math.max(1, Math.min(3, step || 3))) / 3
    );
    var paths = strokes
      .slice(0, count)
      .map(function (stroke) {
        var p = stroke.p;
        var d = 'M' + p[0] + ' ' + p[1];
        for (var i = 2; i < p.length; i += 2) d += 'L' + p[i] + ' ' + p[i + 1];
        return '<path d="' + d + '"/>';
      })
      .join('');
    return (
      '<svg viewBox="-40 -40 1080 1080" aria-hidden="true" focusable="false">' +
      '<g fill="none" stroke="#4A3B55" stroke-width="14" stroke-linecap="round" stroke-linejoin="round">' +
      paths +
      '</g></svg>'
    );
  }

  return { get: get, svg: svg };
